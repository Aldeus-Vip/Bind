function fix(node){
  const w = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  for(let n; (n = w.nextNode());){
    let v = n.nodeValue, o = v;
    for(const [re, to] of REPLACE) v = v.replace(re, to);
    if(v !== o) n.nodeValue = v;
  }
}
